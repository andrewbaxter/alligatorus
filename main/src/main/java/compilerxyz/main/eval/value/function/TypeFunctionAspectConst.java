@BuiltinPath("eval.aspect_lookup")
@BuiltinFull(uniqueId = 6108L, function = true)
public record TypeFunctionAspectConst() implements Aspect, Type {

    static final JavaInternalName INTNAME_TYPE = JavaInternalName.fromClass(Type.class);
    static final JavaMethodDescriptor DESC_TYPE_ASPECT = JavaMethodDescriptor.fromParts(
            JavaDataDescriptor.fromClass(compilerxyz.prelude.util.Opt.class),
            JavaDataDescriptor.fromClass(ExprContext.class),
            JavaDataDescriptor.fromClass(compilerxyz.main.eval.Unique.class));

    @Override
    public String typeDesc() {
        return "fn-aspect";
    }

    @Override
    public Opt<Aspect> typeAspect(ExprContext xx, Unique key) {
        if (key.equals(GenTrivialIdentityAspects.TYPE_FUNCTION_ASPECT_CONST_IDENTITY)) {
            return Opt.some(this);
        }
        if (key.equals(GenAspectFunction.AspectId)) {
            return Opt.some(new AspectFunctionFunctionAspectConst(this));
        }
        return Opt.none();
    }

    @Override
    public EResult<CodeValue> typeCastFrom(ExprContext xx, QExprId loc, CodeValue cv) {
        throw new UnsupportedOperationException(
                getClass().getSimpleName() + "::typeCastFrom unreachable (typeCanCastFrom returned false)");
    }

    @Override
    public boolean typeIsEqual(ExprContext xx, Type other) {
        return other.typeAspect(xx, GenTrivialIdentityAspects.TYPE_FUNCTION_ASPECT_CONST_IDENTITY)
                .optIsSome();
    }

    @Override
    public boolean typeCanCastFrom(ExprContext xx, QExprId loc, Type sourceType) {
        return false;
    }

    @Override
    public boolean typeCanCastTo(ExprContext xx, QExprId loc, Type destType) {
        return false;
    }

    @Override
    public EResult<CodeValue> typeCastTo(ExprContext xx, QExprId loc, CodeValue cv, Type destType) {
        throw new UnsupportedOperationException(
                getClass().getSimpleName() + "::typeCastTo unreachable (typeCanCastTo returned false)");
    }

    @Override
    public Opt<ArtifactExporter> typeExporter() {
        return Opt.none();
    }
}
