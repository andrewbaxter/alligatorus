  private static Object implBuiltinInterface(
      ExprContext xx, compilerxyz.gen.SourceObjectBuilder sor, Object arg, String ifaceField) {
    var record = recordToConstKeyExprMap(arg);
    var dtData = sor.type_;
    var ds = lookupDefSet(xx, dtData.setId);
    var vx = xx.vx;
    var builtinIfaces =
        compilerxyz.eval.value.source_interface.BuiltinInterfaceRegistry.bundle(vx.ix.importState);
    compilerxyz.eval.value.source_interface.SourceInterfaceData ifaceData;
    try {
      ifaceData =
          (compilerxyz.eval.value.source_interface.SourceInterfaceData)
              compilerxyz.gen.GenBuiltinInterfaces.class.getField(ifaceField).get(builtinIfaces);
    } catch (ReflectiveOperationException e) {
      throw new IllegalStateException(
          "DynRuntime.implBuiltinInterface: missing builtin interface field '"
              + ifaceField
              + "'",
          e);
    }
    var impl =
        new compilerxyz.eval.value.source_object.SourceObjectInterfaceImplData(ifaceData);
    for (int idx = 0; idx < ifaceData.methods.size(); idx++) {
      var im = ifaceData.methods.get(idx);
      var ckey = new compilerxyz.eval.ConstKey.Str(im.name);
      var expr = record.get(ckey);
      if (expr == null) {
        throw new IllegalStateException(
            "Missing implementation for builtin interface method '" + im.name + "'");
      }
      var entryId = ds.nextEntryId.next();
      var mImpl =
          new compilerxyz.eval.value.source_object.SourceObjectInterfaceMethodImplData(idx);
      mImpl.implExpr = expr;
      mImpl.bindingId = new compilerxyz.eval.BindingId.Def(ds.defSetId, entryId);
      impl.methodImpls.add(mImpl);
    }
    dtData.interfaceImpls.add(impl);
    return null;
  }

  private static Map<compilerxyz.eval.ConstKey, Expr> recordToConstKeyExprMap(Object arg) {
    if (!(arg instanceof Map<?, ?> rawMap)) {
      throw new IllegalStateException(
          "DynRuntime.recordToConstKeyExprMap: expected Map, got "
              + (arg == null ? "null" : arg.getClass()));
    }
    var out = new java.util.LinkedHashMap<compilerxyz.eval.ConstKey, Expr>();
    for (var entry : rawMap.entrySet()) {
      compilerxyz.eval.ConstKey ckey;
      var k = entry.getKey();
      if (k instanceof compilerxyz.eval.ConstKey ck) {
        ckey = ck;
      } else if (k instanceof String s) {
        ckey = parseConstKeyCanonical(s);
      } else {
        throw new IllegalStateException(
            "DynRuntime.recordToConstKeyExprMap: unsupported key type "
                + (k == null ? "null" : k.getClass()));
      }
      var v = entry.getValue();
      Expr expr;
      if (v instanceof Expr e) {
        expr = e;
      } else if (v instanceof compilerxyz.eval.expr.StagedExprCell cell) {
        var inner = cell.take();
        if (!(inner instanceof Expr e)) {
          throw new IllegalStateException(
              "DynRuntime.recordToConstKeyExprMap: StagedExprCell did not contain Expr, got "
                  + (inner == null ? "null" : inner.getClass()));
        }
        expr = e;
      } else {
        throw new IllegalStateException(
            "DynRuntime.recordToConstKeyExprMap: expected Expr or StagedExprCell value, got "
                + (v == null ? "null" : v.getClass()));
      }
      out.put(ckey, expr);
    }
    return out;
  }

  private static compilerxyz.eval.ConstKey parseConstKeyCanonical(String s) {
    if (s.length() >= 2 && s.charAt(0) == '"' && s.charAt(s.length() - 1) == '"') {
      var inner = s.substring(1, s.length() - 1);
      var sb = new StringBuilder(inner.length());
      for (int i = 0; i < inner.length(); i++) {
        var c = inner.charAt(i);
        if (c == '\\' && i + 1 < inner.length()) {
          sb.append(inner.charAt(++i));
        } else {
          sb.append(c);
        }
      }
      return new compilerxyz.eval.ConstKey.Str(sb.toString());
    }
    return new compilerxyz.eval.ConstKey.Uint(Long.parseUnsignedLong(s));
  }

  private static Unique freshUnique(ExprContext xx) {
    var vx = xx.vx;
    var compileId = new compilerxyz.eval.CompileId(vx.ix.importState, vx.ix.sourceId);
    return new Unique.Source(compileId, vx.uniqueCounter.next());
  }

  private static compilerxyz.eval.DefinitionSet lookupDefSet(
      ExprContext xx, compilerxyz.eval.DefSetId id) {
    if (id == null) {
      throw new IllegalStateException("DynRuntime: definition set id is null");
    }
    var vx = xx.vx;
    var ds = vx.definitionSets.get(id);
    if (ds == null) {
      throw new IllegalStateException(
          "DynRuntime: definition set " + id + " not found in EvalContext.definitionSets");
    }
    return ds;
  }

  private sealed interface StageLowerValue {
    record Expr(compilerxyz.eval.Expr expr) implements StageLowerValue {}

    record Val(Value value) implements StageLowerValue {}
  }

  private static Expr cloneWithLowerSubstitutions(
      Expr expr,
      int sd,
      int ld,
      java.util.Iterator<StageLowerValue> values,
      java.util.Iterator<CodeValue> grafts) {
    var loc = expr.loc();
    return switch (expr.variant()) {
      case Expr.Lower lower -> {
        var newLd = ld + 1;
        if (newLd - sd == 1) {
          if (!values.hasNext()) {
            throw new IllegalStateException(
                "__stage: not enough lower values for substitution");
          }
          yield switch (values.next()) {
            case StageLowerValue.Expr e -> e.expr();
            case StageLowerValue.Val v ->
                new Expr(loc, new Expr.Literal(Expr.LitValue.once(v.value())));
          };
        }
        yield new Expr(
            loc,
            new Expr.Lower(
                cloneWithLowerSubstitutions(lower.expr(), sd, newLd, values, grafts)));
      }
      case Expr.Stage stage ->
          new Expr(
              loc,
              new Expr.Stage(
                  cloneWithLowerSubstitutions(stage.expr(), sd + 1, ld, values, grafts)));
      case Expr.Graft graft -> {
        Expr.Graft next =
            switch (graft) {
              case Expr.Graft.Pending p -> {
                if (sd == 0) {
                  if (!grafts.hasNext()) {
                    throw new IllegalStateException(
                        "__stage: not enough graft values for substitution");
                  }
                  yield new Expr.Graft.Evaluated(grafts.next());
                }
                yield new Expr.Graft.Pending(
                    cloneWithLowerSubstitutions(p.expr(), sd, ld, values, grafts));
              }
              case Expr.Graft.Evaluated e -> e;
            };
        yield new Expr(loc, next);
      }
      case Expr.Literal lit -> expr;
      case Expr.ScopeUse u -> expr;
      case Expr.Import imp -> expr;
      case Expr.As a ->
          new Expr(
              loc,
              new Expr.As(
                  cloneWithLowerSubstitutions(a.base(), sd, ld, values, grafts),
                  cloneWithLowerSubstitutions(a.target(), sd, ld, values, grafts)));
      case Expr.Call c ->
          new Expr(
              loc,
              new Expr.Call(
                  cloneWithLowerSubstitutions(c.func(), sd, ld, values, grafts),
                  cloneWithLowerSubstitutions(c.arg(), sd, ld, values, grafts)));
      case Expr.Bind b ->
          new Expr(
              loc,
              new Expr.Bind(
                  cloneWithLowerSubstitutions(b.base(), sd, ld, values, grafts),
                  cloneWithLowerSubstitutions(b.value(), sd, ld, values, grafts)));
      case Expr.Set s ->
          new Expr(
              loc,
              new Expr.Set(
                  cloneWithLowerSubstitutions(s.base(), sd, ld, values, grafts),
                  cloneWithLowerSubstitutions(s.value(), sd, ld, values, grafts)));
      case Expr.Field f ->
          new Expr(
              loc,
              new Expr.Field(
                  cloneWithLowerSubstitutions(f.base(), sd, ld, values, grafts),
                  cloneWithLowerSubstitutions(f.key(), sd, ld, values, grafts)));
      case Expr.Seq seq -> {
        var newExprs = new TList<Expr>();
        for (var sub : seq.exprs()) {
          newExprs.add(cloneWithLowerSubstitutions(sub, sd, ld, values, grafts));
        }
        yield new Expr(loc, new Expr.Seq(newExprs));
      }
      case Expr.Tuple tup -> {
        var newElems = new TList<Expr>();
        for (var sub : tup.elements()) {
          newElems.add(cloneWithLowerSubstitutions(sub, sd, ld, values, grafts));
        }
        yield new Expr(loc, new Expr.Tuple(newElems));
      }
      case Expr.Record rec -> {
        var newEntries = new TList<Expr.RecordEntry>();
        for (var entry : rec.entries()) {
          newEntries.add(
              new Expr.RecordEntry(
                  cloneWithLowerSubstitutions(entry.key(), sd, ld, values, grafts),
                  cloneWithLowerSubstitutions(entry.value(), sd, ld, values, grafts)));
        }
        yield new Expr(loc, new Expr.Record(newEntries));
      }
      case Expr.If ifExpr -> {
        var newConds = new TList<Expr.ConditionBranch>();
        for (var branch : ifExpr.conditions()) {
          newConds.add(
              new Expr.ConditionBranch(
                  cloneWithLowerSubstitutions(branch.condition(), sd, ld, values, grafts),
                  cloneWithLowerSubstitutions(branch.body(), sd, ld, values, grafts)));
        }
        Opt<Expr> newElse;
        if (ifExpr.else_() instanceof Opt.Some<Expr> some) {
          newElse = Opt.some(cloneWithLowerSubstitutions(some.value(), sd, ld, values, grafts));
        } else {
          newElse = Opt.none();
        }
        yield new Expr(loc, new Expr.If(newConds, newElse));
      }
      case Expr.OperatorLt op ->
          new Expr(
              loc,
              new Expr.OperatorLt(
                  cloneWithLowerSubstitutions(op.base(), sd, ld, values, grafts),
                  cloneWithLowerSubstitutions(op.reference(), sd, ld, values, grafts)));
      case Expr.OperatorEq op ->
          new Expr(
              loc,
              new Expr.OperatorEq(
                  cloneWithLowerSubstitutions(op.base(), sd, ld, values, grafts),
                  cloneWithLowerSubstitutions(op.reference(), sd, ld, values, grafts)));
      case Expr.OperatorAdd op ->
          new Expr(
              loc,
              new Expr.OperatorAdd(
                  cloneWithLowerSubstitutions(op.base(), sd, ld, values, grafts),
                  cloneWithLowerSubstitutions(op.reference(), sd, ld, values, grafts)));
      case Expr.Foreach fe ->
          new Expr(
              loc,
              new Expr.Foreach(
                  cloneWithLowerSubstitutions(fe.base(), sd, ld, values, grafts),
                  cloneWithLowerSubstitutions(fe.elementKey(), sd, ld, values, grafts),
                  cloneWithLowerSubstitutions(fe.body(), sd, ld, values, grafts)));
      case Expr.Match m -> {
        var newCases = new TList<Expr.MatchBranch>();
        for (var c : m.cases()) {
          newCases.add(
              new Expr.MatchBranch(
                  cloneWithLowerSubstitutions(c.condition(), sd, ld, values, grafts),
                  cloneWithLowerSubstitutions(c.body(), sd, ld, values, grafts)));
        }
        Opt<Expr> newFallback;
        if (m.fallback() instanceof Opt.Some<Expr> some) {
          newFallback = Opt.some(cloneWithLowerSubstitutions(some.value(), sd, ld, values, grafts));
        } else {
          newFallback = Opt.none();
        }
        yield new Expr(
            loc,
            new Expr.Match(
                cloneWithLowerSubstitutions(m.base(), sd, ld, values, grafts),
                newCases,
                cloneWithLowerSubstitutions(m.elementKey(), sd, ld, values, grafts),
                newFallback));
      }
      case Expr.Try t -> {
        Opt<Expr.TryCatch> newCatch;
        if (t.catchClause() instanceof Opt.Some<Expr.TryCatch> someCatch) {
          var c = someCatch.value();
          newCatch =
              Opt.some(
                  new Expr.TryCatch(
                      cloneWithLowerSubstitutions(c.bindingName(), sd, ld, values, grafts),
                      cloneWithLowerSubstitutions(c.exceptionType(), sd, ld, values, grafts),
                      cloneWithLowerSubstitutions(c.body(), sd, ld, values, grafts)));
        } else {
          newCatch = Opt.none();
        }
        Opt<Expr> newFinally;
        if (t.finallyBlock() instanceof Opt.Some<Expr> someFin) {
          newFinally = Opt.some(cloneWithLowerSubstitutions(someFin.value(), sd, ld, values, grafts));
        } else {
          newFinally = Opt.none();
        }
        yield new Expr(
            loc,
            new Expr.Try(
                cloneWithLowerSubstitutions(t.body(), sd, ld, values, grafts),
                newCatch,
                newFinally));
      }
    };
  }
