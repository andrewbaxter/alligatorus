  public static compilerxyz.eval.value.source_interface.InterfaceData srcObjectImplAspect(
      ExprContext xx, compilerxyz.gen.SourceObjectBuilder sor, Object recordArg) {
    var record = recordToConstKeyExprMap(recordArg);
    var dtData = sor.type_;
    var ds = lookupDefSet(xx, dtData.setId);
    var identity = freshUnique(xx);
    var ifaceData =
        new compilerxyz.eval.value.source_interface.InterfaceData(
            ds.defSetId, identity, null, ds);
    ds.interfaces.add(ifaceData);
    ifaceData.isAspect = true;
    var methodNames = new compilerxyz.util.TList<String>();
    for (var k : record.keySet()) {
      if (k instanceof compilerxyz.eval.ConstKey.Str s) {
        methodNames.add(s.value());
      } else {
        methodNames.add(k.toCanonical());
      }
    }
    for (var imName : methodNames) {
      var fieldName =
          "_im" + compilerxyz.eval.DefinitionSet.nextInterfaceMethodId(ds);
      var im =
          new compilerxyz.eval.value.source_interface.InterfaceMethodData(imName, fieldName);
      im.argType = new compilerxyz.eval.value.any.TypeAnyDynamic();
      im.retType = new compilerxyz.eval.value.any.TypeAnyDynamic();
      ifaceData.methods.add(im);
    }
    var aspectUniqueField =
        "_im" + compilerxyz.eval.DefinitionSet.nextInterfaceMethodId(ds);
    var aspectIdMethod =
        new compilerxyz.eval.value.source_interface.InterfaceMethodData(
            "aspect_id", aspectUniqueField);
    aspectIdMethod.argType = new compilerxyz.eval.value.tuple.Tuple(compilerxyz.util.Opt.none(), new compilerxyz.util.TList<>());
    aspectIdMethod.retType = new compilerxyz.eval.value.unique.TypeUnique();
    ifaceData.methods.add(aspectIdMethod);
    var impl =
        new compilerxyz.eval.value.source_object.SourceObjectInterfaceImplData(ifaceData);
    var allMethodNames = new compilerxyz.util.TList<String>();
    for (var m : ifaceData.methods) {
      allMethodNames.add(m.name);
    }
    for (int idx = 0; idx < allMethodNames.size(); idx++) {
      var imName = allMethodNames.get(idx);
      if (imName.equals("aspect_id")) {
        var aspectIdEntryId = ds.nextEntryId.next();
        var uniqueLiteral =
            new Expr(
                new compilerxyz.eval.QExprId(new compilerxyz.eval.SourceId(0), 0L),
                new Expr.Literal(
                    Expr.LitValue.shared(
                        new compilerxyz.eval.value.unique.ValueUnique(identity))));
        var mImpl =
            new compilerxyz.eval.value.source_object.SourceObjectInterfaceMethodImplData(idx);
        mImpl.implExpr = uniqueLiteral;
        mImpl.bindingId = new compilerxyz.eval.BindingId.Def(ds.defSetId, aspectIdEntryId);
        impl.methodImpls.add(mImpl);
        continue;
      }
      var ckey = new compilerxyz.eval.ConstKey.Str(imName);
      var expr = record.get(ckey);
      if (expr == null) {
        throw new IllegalStateException(
            "Missing implementation for aspect method '" + imName + "'");
      }
      var entryId = ds.nextEntryId.next();
      var mImpl =
          new compilerxyz.eval.value.source_object.SourceObjectInterfaceMethodImplData(idx);
      mImpl.implExpr = expr;
      mImpl.bindingId = new compilerxyz.eval.BindingId.Def(ds.defSetId, entryId);
      impl.methodImpls.add(mImpl);
    }
    dtData.interfaceImpls.add(impl);
    return ifaceData;
  }

